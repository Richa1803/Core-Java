package in.co.rays.array;

public class CharArray {
	
	public static void main(String []args) {
		char []c = {'r','i','c','h','a'};
		
		for(int i =0; i<c.length; i++)
		{
			System.out.print(c[i]);
			//System.out.println();
			
			System.out.println("=" +i);
		}
		System.out.println("--------------------");
		System.out.println();

	
	}

}
